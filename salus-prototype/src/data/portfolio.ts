const VALUATION_DATES: readonly string[] = ['2025-12-31', '2026-03-31', '2026-06-30'];

function buildAssets(): Asset[] {
  const random = mulberry32(SEED);
  const assets: Asset[] = [];
  let counter = 0;

  for (const site of sites) {
    const count = ASSET_COUNTS[site.id] ?? 1;
    const weights: number[] = [];
    for (let index = 0; index < count; index += 1) {
      weights.push(0.5 + random());
    }
    const totalWeight = weights.reduce((total, weight) => total + weight, 0);

    for (let index = 0; index < count; index += 1) {
      counter += 1;
      const weight = weights[index] ?? 1;
      const declaredValueSgd = Math.round((site.tivSgd * weight) / totalWeight);
      const pmlSgd = Math.round(declaredValueSgd * (0.3 + random() * 0.15));
      const dateIndex = Math.floor(random() * VALUATION_DATES.length);
      assets.push({
        id: `ast-${String(counter).padStart(2, '0')}`,
        siteId: site.id,
        label: `${site.name} — ${ASSET_LABELS[index % ASSET_LABELS.length] ?? 'Asset'}`,
        declaredValueSgd,
        pmlSgd,
        valuationDate: VALUATION_DATES[dateIndex] ?? '2026-06-30',
      });
    }
  }

  return assets;
}

const assets = buildAssets();

function firstAssetId(siteId: string): string {
  const asset = assets.find((candidate) => candidate.siteId === siteId);
  if (asset === undefined) {
    throw new Error(`Seed has no asset for ${siteId}`);
  }
  return asset.id;
}

